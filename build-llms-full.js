#!/usr/bin/env node
/*
 * Generates source/llms-full.txt from the 0.15 documentation pages.
 *
 * - The header (summary, Vocabulary, When to choose, TypeScript) is taken from
 *   source/llms.txt so the two files never drift apart.
 * - Pages are emitted in sidebar order (source/_data/0.15/sidebar.yml), each
 *   starting with `# <title>` and a `Source:` URL, so an LLM can cite the page.
 * - Hexo `{% note %}` tags become blockquotes, relative links and image paths
 *   become absolute URLs, iframes are dropped.
 *
 * Usage: node build-llms-full.js   (or `npm run llms`)
 */
const fs = require("fs");
const path = require("path");

const SITE_URL = "https://moleculer.services";
const DOCS_VERSION = "0.15";
const DOCS_DIR = path.join(__dirname, "source", "docs", DOCS_VERSION);
const SIDEBAR = path.join(__dirname, "source", "_data", DOCS_VERSION, "sidebar.yml");
const LLMS_TXT = path.join(__dirname, "source", "llms.txt");
const OUT = path.join(__dirname, "source", "llms-full.txt");
const DOCS_URL = `${SITE_URL}/docs/${DOCS_VERSION}/`;

// --- page list from the sidebar (only local .md pages) ---------------------
function pagesFromSidebar() {
	const pages = [];
	for (const line of fs.readFileSync(SIDEBAR, "utf8").split("\n")) {
		const m = line.match(/^\s+[\w-]+:\s+(.+\.html)\s*$/);
		if (!m) continue;
		const target = m[1].trim();
		if (/^(https?:)?\/\//.test(target) || target.startsWith("/")) continue;
		const file = path.join(DOCS_DIR, target.replace(/\.html$/, ".md"));
		if (fs.existsSync(file) && !pages.includes(target)) pages.push(target);
	}
	return pages;
}

// --- header from llms.txt --------------------------------------------------
function header() {
	const src = fs.readFileSync(LLMS_TXT, "utf8");
	const end = src.indexOf("\n## Getting Started");
	const head = (end === -1 ? src : src.slice(0, end))
		.replace(/^# Moleculer\s*$/m, "# Moleculer — Full Documentation")
		.trimEnd();
	return (
		head +
		"\n\n" +
		"> This file contains the full text of the Moleculer " +
		DOCS_VERSION +
		" documentation. Every page starts with a `# Title` heading and a `Source:` line with its canonical URL. " +
		"The short index is at " +
		SITE_URL +
		"/llms.txt. Generated by `build-llms-full.js` — do not edit by hand.\n"
	);
}

// --- content transforms ----------------------------------------------------
function splitFrontMatter(raw) {
	// Pages start with `title: X\n---\n` (no leading `---`).
	const m = raw.match(/^(?:---\n)?([\s\S]*?)\n---\n/);
	if (!m) return { title: null, body: raw };
	const fm = m[1];
	const t = fm.match(/^title:\s*(.+)$/m);
	return { title: t ? t[1].trim().replace(/^["']|["']$/g, "") : null, body: raw.slice(m[0].length) };
}

function convertNotes(body) {
	const out = [];
	let inNote = false;
	for (const line of body.split("\n")) {
		const open = line.match(/^\s*\{%\s*note\s+(\w+)?\s*(.*?)\s*%\}\s*$/);
		if (open) {
			inNote = true;
			const kind = (open[1] || "note").toLowerCase();
			const label = { warn: "Warning", warning: "Warning", info: "Note", success: "Tip", danger: "Danger" }[kind] || "Note";
			out.push(`> **${open[2] ? open[2] : label}**`);
			continue;
		}
		if (/^\s*\{%\s*endnote\s*%\}\s*$/.test(line)) {
			inNote = false;
			continue;
		}
		out.push(inNote ? (line.trim() === "" ? ">" : `> ${line}`) : line);
	}
	return out.join("\n");
}

function absolutizeLinks(body) {
	return (
		body
			// [text](page.html#anchor) / [text](assets/x.png) → absolute docs URL
			.replace(/\]\(((?![a-z]+:|\/|#|mailto:)[^)\s]+)\)/gi, (m, href) => `](${DOCS_URL}${href})`)
			// [text](/laboratory/x.html) → site-absolute
			.replace(/\]\((\/[^)\s]+)\)/g, (m, href) => `](${SITE_URL}${href})`)
			// <img src="assets/..."> inside HTML
			.replace(/src="((?!https?:|\/)[^"]+)"/g, (m, src) => `src="${DOCS_URL}${src}"`)
	);
}

// Some pages use `#` as their top heading level, others `##`. The page title
// is emitted as `#`, so demote in-page headings by one level on pages that
// have their own `#` headings (ignoring `#` lines inside code fences).
function demoteHeadings(body) {
	const lines = body.split("\n");
	let fenced = false;
	const isHeading = l => !fenced && /^#{1,5} /.test(l);
	const hasH1 = lines.some(l => {
		if (/^\s*(```|~~~)/.test(l)) fenced = !fenced;
		return !fenced && /^# /.test(l);
	});
	fenced = false;
	if (!hasH1) return body;
	return lines
		.map(l => {
			if (/^\s*(```|~~~)/.test(l)) fenced = !fenced;
			return isHeading(l) ? "#" + l : l;
		})
		.join("\n");
}

function stripIframes(body) {
	return body.replace(/<iframe[\s\S]*?<\/iframe>/gi, "").replace(/\n{3,}/g, "\n\n");
}

function renderPage(target) {
	const file = path.join(DOCS_DIR, target.replace(/\.html$/, ".md"));
	const { title, body } = splitFrontMatter(fs.readFileSync(file, "utf8"));
	const content = stripIframes(absolutizeLinks(convertNotes(demoteHeadings(body)))).trim();
	return `# ${title || target}\n\nSource: ${DOCS_URL}${target}\n\n${content}\n`;
}

// --- main ------------------------------------------------------------------
const pages = pagesFromSidebar();
if (pages.length === 0) throw new Error("No pages found in " + SIDEBAR);

const output = [header(), ...pages.map(renderPage)].join("\n---\n\n");
fs.writeFileSync(OUT, output);
console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${pages.length} pages, ${output.split("\n").length} lines`);
